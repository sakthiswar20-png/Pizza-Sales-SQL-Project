-- 17.Which month generated the highest revenue.

SELECT DATE_FORMAT(o.order_date, '%b') AS sales_month,
       SUM(od.quantity * p.price) AS mouthly_revenue
FROM pizzas AS p
INNER JOIN order_details AS od
    ON p.pizza_id = od.pizza_id
INNER JOIN orders AS o
    on o.order_id = od.order_id
GROUP BY DATE_FORMAT(o.order_date, '%b') 
ORDER BY mouthly_revenue DESC
LIMIT 1;

-- 18.Which day of the week has the highest number of orders.

SELECT
