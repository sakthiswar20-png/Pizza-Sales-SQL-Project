-- 21.Find pizzas priced above the average pizza price.

SELECT pt.name,
	   p.price
FROM pizzas AS p
INNER JOIN pizza_types AS pt
   ON p.pizza_type_id = pt.pizza_type_id      
WHERE p.price > (SELECT AVG(p.price)
FROM pizzas);

 -- 22.Find categories whose revenue is greater than the average category revenue.
 
SELECT
    pt.category,
    SUM(od.quantity * p.price) AS total_revenue
FROM order_details AS od
INNER JOIN pizzas AS p
    ON od.pizza_id = p.pizza_id
INNER JOIN pizza_types AS pt
    ON p.pizza_type_id = pt.pizza_type_id
GROUP BY pt.category
HAVING SUM(od.quantity * p.price) > (
    SELECT AVG(category_revenue)
    FROM (SELECT
		  SUM(od2.quantity * p2.price) AS category_revenue
        FROM order_details AS od2
        INNER JOIN pizzas AS p2
            ON od2.pizza_id = p2.pizza_id
        INNER JOIN pizza_types AS pt2
            ON p2.pizza_type_id = pt2.pizza_type_id
        GROUP BY pt2.category) AS avg_revenue)
ORDER BY total_revenue DESC;


-- 23.Rank pizzas based on total quantity sold.

SELECT pt.name AS pizza_name,
       SUM(od.quantity) AS total_quantity,
       RANK() OVER (ORDER BY SUM(od.quantity) DESC) AS sales_rank
FROM order_details AS od
INNER JOIN pizzas AS p
    ON od.pizza_id = p.pizza_id
INNER JOIN pizza_types AS pt
    ON p.pizza_type_id = pt.pizza_type_id
GROUP BY pt.name;


